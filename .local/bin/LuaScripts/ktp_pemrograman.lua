-- ================= KONFIGURASI =================
local function get_KTP_chapters()
    local chapters = {}

    -- Mengambil list dari direktori
    local pipe = io.popen([[find "/data/data/com.termux/files/home/storage/projects/EbookLauncher/KTP_Pemrograman" -type f -name "*.txt"]])

    for path in pipe:lines() do
        local name = path:match("([^/]+)%.txt$")
        if name then
            table.insert(chapters, name)
        end
    end

    pipe:close()

    table.sort(chapters, function(a, b)
        return a:lower() < b:lower()
    end)

    return chapters
end

local chapters_KTP = get_KTP_chapters()

if not chapters_KTP or #chapters_KTP == 0 then
    print("[Error]: Chapters tidak ditemukan di ktp.lua")
    os.exit(1)
end

-- FIX: Menghapus *.txt di akhir path agar tidak bertabrakan saat digabung
local KTP_base_path = "/data/data/com.termux/files/home/storage/projects/EbookLauncher/KTP_Pemrograman/"
local KTP_Header = "====================================== START\n"

local function KTP_cmd(c)
    os.execute(c)
end

local function KTP_show_lists()
    print("Silakan Pilih KTP :\n")
    for i, c in ipairs(chapters_KTP) do
        print(string.format("[%d] %s", i, c))
    end
end

local function KTP_show_cover()
    KTP_cmd("clear")
    print("============== KTP Pemrograman =============")
    print("--------------------------------------------")
    print(" Ini adalah Kartu Tanda bahasa Pemrograman\n")
    KTP_show_lists()
end

local function KTP_validate_file(KTP_path)
    local KTP_f, err = io.open(KTP_path, "r")
    
    if not KTP_f then
        KTP_f = io.open(KTP_path, "w")
        if KTP_f then
            KTP_f:write(KTP_Header)
            KTP_f:write("\n")
            KTP_f:close()
            return true
        else
            print("============ ⚠️ ACCESE DENIED =============")
            print("Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.")
            print("\nHow to fix this:\n")
            print("1. Delete the existing file.")
            print("2. Re-run the script and select your target\n   index.")
            print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
            print("Once regenerated, you can manually edit the file without any issues.")
            print("\n--------------------------------------------")
            return false
        end
    end
    
    KTP_f:close()
    return true
end

local function KTP_read_file(KTP_path)
    local KTP_f = io.open(KTP_path, "r")
    if not KTP_f then
        print("❌ Gagal membuka eKtp")
        return
    end

    local content = KTP_f:read("*a")
    KTP_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("Kegabutan HaQiQi ---------------------------")
    print("====================================== END\n")
end

-- Fungsi Lingkungan Shell / UI
local function KTP_interactive()
    KTP_show_cover()

    while true do  
        io.write("\n> ")
        local KTP_user_input = io.read()  
        
        if KTP_user_input == "q" then
            print("bye, Happy Learning..!!")
            break
        elseif KTP_user_input == "l" then 
            KTP_cmd("clear")
            KTP_show_lists()
        else
            local KTP_index = tonumber(KTP_user_input)
            
            if KTP_index and chapters_KTP[KTP_index] then
                local KTP_chapter_name = chapters_KTP[KTP_index]  
                local KTP_file_path = KTP_base_path .. KTP_chapter_name .. ".txt"  
                  
                KTP_cmd("clear")  
                if KTP_validate_file(KTP_file_path) then  
                    KTP_read_file(KTP_file_path)
                    print("=================== Quit(q) Lists(l) ===")
                end 
            else  
                print("⚠️ Invalid chapter!")
                io.write("Press enter to continue...")
                io.read() 
            end  
        end  
    end
end

-- ================= ARGUMENT PARSING =================
local arg1 = arg[1]
local arg2 = arg[2]

if not arg1 then
    -- Default tanpa argument
    print("Gunakan argument: --ui, --list, --list <no>, atau <Nama KTP>")
    print("Contoh: luajit ktp.lua --ui")
elseif arg1 == "--ui" or arg1 == "-u" then
    -- Mode 1: Masuk UI Environment
    KTP_interactive()
elseif arg1 == "--list" or arg1 == "-l" then
    if arg2 then
        -- Mode 3: Print berdasarkan Nomor Index
        local KTP_index = tonumber(arg2)
        if KTP_index and chapters_KTP[KTP_index] then
            local KTP_chapter_name = chapters_KTP[KTP_index]
            local KTP_file_path = KTP_base_path .. KTP_chapter_name .. ".txt"
            
            if KTP_validate_file(KTP_file_path) then
                KTP_read_file(KTP_file_path)
            end
        else
            print("❌ Index " .. tostring(arg2) .. " tidak valid atau tidak ditemukan!")
        end
    else
        -- Mode 2: Tampilkan semua list
        KTP_show_lists()
    end
else
    -- Mode 4: Print berdasarkan Nama (Case-Insensitive search)
    local found_name = nil
    for _, chapter in ipairs(chapters_KTP) do
        if chapter:lower() == arg1:lower() then
            found_name = chapter
            break
        end
    end

    if found_name then
        local KTP_file_path = KTP_base_path .. found_name .. ".txt"
        if KTP_validate_file(KTP_file_path) then
            KTP_read_file(KTP_file_path)
        end
    else
        print("❌ KTP dengan nama '" .. arg1 .. "' tidak ditemukan!")
    end
end
