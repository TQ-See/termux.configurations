-- ================= KONFIGURASI =================
local function get_LUA_chapters()
    local chapters = {}

    -- Mengambil list dari direktori
    local pipe = io.popen([[find "/data/data/com.termux/files/home/storage/projects/EbookLauncher/Lua_Ebook" -type f -name "*.txt"]])

    for path in pipe:lines() do
        local name = path:match("([^/]+)%.txt$")
        if name then
            table.insert(chapters, name)
        end
    end

    pipe:close()

    table.sort(chapters, function(a, b)
        return a:lower() < b:lower()
    end)

    return chapters
end

local chapters_LUA = get_LUA_chapters()

if not chapters_LUA or #chapters_LUA == 0 then
    print("[Error]: Chapters tidak ditemukan di LUA folder")
    os.exit(1)
end

-- FIX: Menghapus *.txt di akhir path agar tidak bertabrakan saat digabung
local LUA_base_path = "/data/data/com.termux/files/home/storage/projects/EbookLauncher/Lua_Ebook/"
local LUA_Header = "====================================== START\n"

local function LUA_cmd(c)
    os.execute(c)
end

local function LUA_show_lists()
    print("Silakan Pilih Chapter :\n")
    for i, c in ipairs(chapters_LUA) do
        print(string.format("[%d] %s", i, c))
    end
end

local function LUA_show_cover()
    LUA_cmd("clear")
    print("============== LUA Pemrograman =============")
    print("--------------------------------------------")
    print(" Ini adalah Kartu Tanda bahasa Pemrograman\n")
    LUA_show_lists()
end

local function LUA_validate_file(LUA_path)
    local LUA_f, err = io.open(LUA_path, "r")
    
    if not LUA_f then
        LUA_f = io.open(LUA_path, "w")
        if LUA_f then
            LUA_f:write(LUA_Header)
            LUA_f:write("\n")
            LUA_f:close()
            return true
        else
            print("============ ⚠️ ACCESE DENIED =============")
            print("Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.")
            print("\nHow to fix this:\n")
            print("1. Delete the existing file.")
            print("2. Re-run the script and select your target\n   index.")
            print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
            print("Once regenerated, you can manually edit the file without any issues.")
            print("\n--------------------------------------------")
            return false
        end
    end
    
    LUA_f:close()
    return true
end

local function LUA_read_file(LUA_path)
    local LUA_f = io.open(LUA_path, "r")
    if not LUA_f then
        print("❌ Gagal membuka Chapter")
        return
    end

    local content = LUA_f:read("*a")
    LUA_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("Kegabutan HaQiQi ---------------------------")
    print("====================================== END\n")
end

-- Fungsi Lingkungan Shell / UI
local function LUA_interactive()
    LUA_show_cover()

    while true do  
        io.write("\n> ")
        local LUA_user_input = io.read()  
        
        if LUA_user_input == "q" then
            print("bye, Happy Learning..!!")
            break
        elseif LUA_user_input == "l" then 
            LUA_cmd("clear")
            LUA_show_lists()
        else
            local LUA_index = tonumber(LUA_user_input)
            
            if LUA_index and chapters_LUA[LUA_index] then
                local LUA_chapter_name = chapters_LUA[LUA_index]  
                local LUA_file_path = LUA_base_path .. LUA_chapter_name .. ".txt"  
                  
                LUA_cmd("clear")  
                if LUA_validate_file(LUA_file_path) then  
                    LUA_read_file(LUA_file_path)
                    print("=================== Quit(q) Lists(l) ===")
                end 
            else  
                print("⚠️ Invalid chapter!")
                io.write("Press enter to continue...")
                io.read() 
            end  
        end  
    end
end

-- ================= ARGUMENT PARSING =================
local arg1 = arg[1]
local arg2 = arg[2]

if not arg1 then
    -- Default tanpa argument
    print("Gunakan argument: --[ui, list, list <ID>]")
    print("Contoh: luajit LUA_Notes.lua --ui")
elseif arg1 == "--ui" or arg1 == "-u" then
    -- Mode 1: Masuk UI Environment
    LUA_interactive()
elseif arg1 == "--list" or arg1 == "-l" then
    if arg2 then
        -- Mode 3: Print berdasarkan Nomor Index
        local LUA_index = tonumber(arg2)
        if LUA_index and chapters_LUA[LUA_index] then
            local LUA_chapter_name = chapters_LUA[LUA_index]
            local LUA_file_path = LUA_base_path .. LUA_chapter_name .. ".txt"
            
            if LUA_validate_file(LUA_file_path) then
                LUA_read_file(LUA_file_path)
            end
        else
            print("❌ Index " .. tostring(arg2) .. " tidak valid atau tidak ditemukan!")
        end
    else
        -- Mode 2: Tampilkan semua list
        LUA_show_lists()
    end
else
    -- Mode 4: Print berdasarkan Nama (Case-Insensitive search)
    local found_name = nil
    for _, chapter in ipairs(chapters_LUA) do
        if chapter:lower() == arg1:lower() then
            found_name = chapter
            break
        end
    end

    if found_name then
        local LUA_file_path = LUA_base_path .. found_name .. ".txt"
        if LUA_validate_file(LUA_file_path) then
            LUA_read_file(LUA_file_path)
        end
    else
        print("❌ LUA dengan nama '" .. arg1 .. "' tidak ditemukan!")
    end
end
