-- ================= KONFIGURASI =================
local function get_RUST_chapters()
    local chapters = {}

    -- Mengambil list dari direktori
    local pipe = io.popen([[find "/data/data/com.termux/files/home/storage/projects/EbookLauncher/Rust_Ebook" -type f -name "*.txt"]])

    for path in pipe:lines() do
        local name = path:match("([^/]+)%.txt$")
        if name then
            table.insert(chapters, name)
        end
    end

    pipe:close()

    table.sort(chapters, function(a, b)
        return a:lower() < b:lower()
    end)

    return chapters
end

local chapters_RUST = get_RUST_chapters()

if not chapters_RUST or #chapters_RUST == 0 then
    print("[Error]: Chapters tidak ditemukan di RUST folder")
    os.exit(1)
end

-- FIX: Menghapus *.txt di akhir path agar tidak bertabrakan saat digabung
local RUST_base_path = "/data/data/com.termux/files/home/storage/projects/EbookLauncher/Rust_Ebook/"
local RUST_Header = "====================================== START\n"

local function RUST_cmd(c)
    os.execute(c)
end

local function RUST_show_lists()
    print("Silakan Pilih Chapter :\n")
    for i, c in ipairs(chapters_RUST) do
        print(string.format("[%d] %s", i, c))
    end
end

local function RUST_show_cover()
    RUST_cmd("clear")
    print("============== RUST Pemrograman =============")
    print("--------------------------------------------")
    print(" Ini adalah Kartu Tanda bahasa Pemrograman\n")
    RUST_show_lists()
end

local function RUST_validate_file(RUST_path)
    local RUST_f, err = io.open(RUST_path, "r")
    
    if not RUST_f then
        RUST_f = io.open(RUST_path, "w")
        if RUST_f then
            RUST_f:write(RUST_Header)
            RUST_f:write("\n")
            RUST_f:close()
            return true
        else
            print("============ ⚠️ ACCESE DENIED =============")
            print("Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.")
            print("\nHow to fix this:\n")
            print("1. Delete the existing file.")
            print("2. Re-run the script and select your target\n   index.")
            print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
            print("Once regenerated, you can manually edit the file without any issues.")
            print("\n--------------------------------------------")
            return false
        end
    end
    
    RUST_f:close()
    return true
end

local function RUST_read_file(RUST_path)
    local RUST_f = io.open(RUST_path, "r")
    if not RUST_f then
        print("❌ Gagal membuka Chapter")
        return
    end

    local content = RUST_f:read("*a")
    RUST_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("Kegabutan HaQiQi ---------------------------")
    print("====================================== END\n")
end

-- Fungsi Lingkungan Shell / UI
local function RUST_interactive()
    RUST_show_cover()

    while true do  
        io.write("\n> ")
        local RUST_user_input = io.read()  
        
        if RUST_user_input == "q" then
            print("bye, Happy Learning..!!")
            break
        elseif RUST_user_input == "l" then 
            RUST_cmd("clear")
            RUST_show_lists()
        else
            local RUST_index = tonumber(RUST_user_input)
            
            if RUST_index and chapters_RUST[RUST_index] then
                local RUST_chapter_name = chapters_RUST[RUST_index]  
                local RUST_file_path = RUST_base_path .. RUST_chapter_name .. ".txt"  
                  
                RUST_cmd("clear")  
                if RUST_validate_file(RUST_file_path) then  
                    RUST_read_file(RUST_file_path)
                    print("=================== Quit(q) Lists(l) ===")
                end 
            else  
                print("⚠️ Invalid chapter!")
                io.write("Press enter to continue...")
                io.read() 
            end  
        end  
    end
end

-- ================= ARGUMENT PARSING =================
local arg1 = arg[1]
local arg2 = arg[2]

if not arg1 then
    -- Default tanpa argument
    print("Gunakan argument: --[ui, list, list <ID>]")
    print("Contoh: luajit RUST_Notes.lua --ui")
elseif arg1 == "--ui" or arg1 == "-u" then
    -- Mode 1: Masuk UI Environment
    RUST_interactive()
elseif arg1 == "--list" or arg1 == "-l" then
    if arg2 then
        -- Mode 3: Print berdasarkan Nomor Index
        local RUST_index = tonumber(arg2)
        if RUST_index and chapters_RUST[RUST_index] then
            local RUST_chapter_name = chapters_RUST[RUST_index]
            local RUST_file_path = RUST_base_path .. RUST_chapter_name .. ".txt"
            
            if RUST_validate_file(RUST_file_path) then
                RUST_read_file(RUST_file_path)
            end
        else
            print("❌ Index " .. tostring(arg2) .. " tidak valid atau tidak ditemukan!")
        end
    else
        -- Mode 2: Tampilkan semua list
        RUST_show_lists()
    end
else
    -- Mode 4: Print berdasarkan Nama (Case-Insensitive search)
    local found_name = nil
    for _, chapter in ipairs(chapters_RUST) do
        if chapter:lower() == arg1:lower() then
            found_name = chapter
            break
        end
    end

    if found_name then
        local RUST_file_path = RUST_base_path .. found_name .. ".txt"
        if RUST_validate_file(RUST_file_path) then
            RUST_read_file(RUST_file_path)
        end
    else
        print("❌ RUST dengan nama '" .. arg1 .. "' tidak ditemukan!")
    end
end
