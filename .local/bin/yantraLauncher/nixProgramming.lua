        if Nix_index and chapters_Nix[Nix_index] then
        -- if Nix_index and Nix_index >= 0 and Nix_index < #chapters_Nix then  
          local Nix_chapter_name = chapters_Nix[Nix_index]  
          local Nix_file_path = Nix_base_path .. Nix_chapter_name .. ".txt"  
              
          Nix_cmd("clear")  
          if Nix_validate_file(Nix_file_path) then  
              Nix_read_file(Nix_file_path)  
          end 
