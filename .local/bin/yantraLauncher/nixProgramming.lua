local Nix_base_path = "/storage/emulated/0/Documents/EbookLauncher/Nix_Ebook/"
local Nix_Header = "====================================== START\n"

  -- lists
  local function Nix_show_lists()
    print("Silakan Pilih chapter : \n")
    for i, c in ipairs(chapters_Nix) do
      print(string.format("[%d] %s", i, c))
    end
  end

  local function Nix_cmd(c)
    if binding and binding.exec then
      binding.exec(c)
    end
  end

  -- Cover
  local function Nix_show_cover()
    Nix_cmd("clear")
    print("=================== Nix ====================")
    print("--------------------------------------------")
    print(" Selamat datang di Ebook pembelajaran Nix\n")
    Nix_show_lists()
  end

  local function Nix_validate_file(Nix_path)
    local Nix_f, err = io.open(Nix_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not Nix_f then
      Nix_f = io.open(Nix_path, "w")
      if Nix_f then
          Nix_f:write(Nix_Header)
          Nix_f:write("\n")
          Nix_f:close()
          return true
      else
          Nix_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          Nix_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          Nix_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== lists(l) quit(q)")
          return false
      end
    end
    return true
  end

  -- Reader
  local function Nix_read_file(Nix_path)
    local Nix_f = io.open(Nix_path, "r")
    if not Nix_f then
      print("❌ Gagal membuka ebook.")
      return
    end

    local content = Nix_f:read("*a")
    Nix_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("=================== Quit(q) Lists(l) === END")
  end

  Nix_show_cover()
  while true do  
