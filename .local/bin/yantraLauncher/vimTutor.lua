local Vim_base_path = "/storage/emulated/0/Documents/EbookLauncher/Vim_Ebook/"
local Vim_Header = "====================================== START\n"

  -- lists
  local function Vim_show_lists()
    print("Silakan Pilih chapter : \n")
    for i, c in ipairs(chapters_Vim) do
      print(string.format("[%d] %s", i, c))
    end
  end

  local function Vim_cmd(c)
    if binding and binding.exec then
      binding.exec(c)
    end
  end

  -- Cover
  local function Vim_show_cover()
    Vim_cmd("clear")
    print("=================== Vim ====================")
    print("--------------------------------------------")
    print(" Selamat datang di Ebook pembelajaran Vim\n")
    Vim_show_lists()
  end

  local function Vim_validate_file(Vim_path)
    local Vim_f, err = io.open(Vim_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not Vim_f then
      Vim_f = io.open(Vim_path, "w")
      if Vim_f then
          Vim_f:write(Vim_Header)
          Vim_f:write("\n")
          Vim_f:close()
          return true
      else
          Vim_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          Vim_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          Vim_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== lists(l) quit(q)")
          return false
      end
    end
    return true
  end

  -- Reader
  local function Vim_read_file(Vim_path)
    local Vim_f = io.open(Vim_path, "r")
    if not Vim_f then
      print("❌ Gagal membuka ebook.")
      return
    end

    local content = Vim_f:read("*a")
    Vim_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("=================== Quit(q) Lists(l) === END")
  end

  Vim_show_cover()
  while true do  
    local Vim_user_input = input()  
    
    -- 1. Cek perintah khusus (String) terlebih dahulu
    if Vim_user_input == "q" then
        print("Bye, Happy Learning...!")
        break

    elseif Vim_user_input == "l" then -- idk why this is causing crash, if u want to try, then try it
        Vim_cmd("clear")
