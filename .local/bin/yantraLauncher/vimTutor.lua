    else
        local Vim_index = tonumber(Vim_user_input)
        -- Validasi apakah input adalah angka DAN berada dalam rentang array yang benar
        if Vim_index and chapters_Vim[Vim_index] then
        -- if Vim_index and Vim_index >= 0 and Vim_index < #chapters_Vim then  
          local Vim_chapter_name = chapters_Vim[Vim_index]  
          local Vim_file_path = Vim_base_path .. Vim_chapter_name .. ".txt"  
              
          Vim_cmd("clear")  
          if Vim_validate_file(Vim_file_path) then  
              Vim_read_file(Vim_file_path)  
          end 
        else  
          print("⚠️ Invalid chapter!")
          input("Press enter...")
        end  
    end  
  end
