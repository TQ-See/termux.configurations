local Rust_Header = "====================================== START\n"

  -- lists
  local function Rust_show_lists()
    print("Silakan Pilih chapter : \n")
    for i, c in ipairs(chapters_Rust) do
      print(string.format("[%d] %s", i, c))
    end
  end

  local function Rust_cmd(c)
    if binding and binding.exec then
      binding.exec(c)
    end
  end

  -- Cover
  local function Rust_show_cover()
    Rust_cmd("clear")
    print("================== Rust ====================")
    print("--------------------------------------------")
    print(" Selamat datang di Ebook pembelajaran Rust\n")
    Rust_show_lists()
  end

  local function Rust_validate_file(Rust_path)
    local Rust_f, err = io.open(Rust_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not Rust_f then
      Rust_f = io.open(Rust_path, "w")
      if Rust_f then
          Rust_f:write(Rust_Header)
          Rust_f:write("\n")
          Rust_f:close()
          return true
      else
          Rust_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          Rust_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          Rust_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== lists(l) quit(q)")
          return false
      end
    end
    return true
  end

  -- Reader
  local function Rust_read_file(Rust_path)
    local Rust_f = io.open(Rust_path, "r")
    if not Rust_f then
      print("❌ Gagal membuka ebook.")
      return
    end

    local content = Rust_f:read("*a")
    Rust_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("=================== Quit(q) Lists(l) === END")
  end

  Rust_show_cover()
