}

local Helix_base_path = "/storage/emulated/0/Documents/EbookLauncher/Helix_Ebook/"
local Helix_Header = "====================================== START\n"

  -- lists
  local function Helix_show_lists()
    print("Silakan Pilih chapter : \n")
    for i, c in ipairs(chapters_Helix) do
      print(string.format("[%d] %s", i, c))
    end
  end

  local function Helix_cmd(c)
    if binding and binding.exec then
      binding.exec(c)
    end
  end

  -- Cover
  local function Helix_show_cover()
    Helix_cmd("clear")
    print("================== Helix ===================")
    print("--------------------------------------------")
    print(" Selamat datang di Ebook pembelajaran Helix\n")
    Helix_show_lists()
  end

  local function Helix_validate_file(Helix_path)
    local Helix_f, err = io.open(Helix_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not Helix_f then
      Helix_f = io.open(Helix_path, "w")
      if Helix_f then
          Helix_f:write(Helix_Header)
          Helix_f:write("\n")
          Helix_f:close()
          return true
      else
          Helix_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          Helix_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          Helix_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== Quit(q) quit(q)")
          return false
      end
    end
    return true
  end

  -- Reader
  local function Helix_read_file(Helix_path)
    local Helix_f = io.open(Helix_path, "r")
    if not Helix_f then
      print("❌ Gagal membuka ebook.")
      return
    end

    local content = Helix_f:read("*a")
    Helix_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("=================== Quit(q) Lists(l) === END")
  end

  Helix_show_cover()
  while true do  
    local Helix_user_input = input()  
    
    -- 1. Cek perintah khusus (String) terlebih dahulu
    if Helix_user_input == "q" then
        print("Bye, Happy Learning..!!")
        break

    elseif Helix_user_input == "l" then -- idk why this is causing crash, if u want to try, then try it
        Helix_cmd("clear")
