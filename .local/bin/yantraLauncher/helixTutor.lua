    else
        local Helix_index = tonumber(Helix_user_input)
        -- Validasi apakah input adalah angka DAN berada dalam rentang array yang benar
        if Helix_index and chapters_Helix[Helix_index] then
        -- if Helix_index and Helix_index >= 0 and Helix_index < #chapters_Helix then  
          local Helix_chapter_name = chapters_Helix[Helix_index]  
          local Helix_file_path = Helix_base_path .. Helix_chapter_name .. ".txt"  
              
          Helix_cmd("clear")  
          if Helix_validate_file(Helix_file_path) then  
              Helix_read_file(Helix_file_path)  
          end 
        else  
          print("⚠️ Invalid chapter!")
          input("Press enter...")
        end  
    end  
  end
