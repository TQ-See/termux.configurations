  local function Lua_validate_file(Lua_path)
    local Lua_f, err = io.open(Lua_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not Lua_f then
      Lua_f = io.open(Lua_path, "w")
      if Lua_f then
          Lua_f:write(Lua_Header)
          Lua_f:write("\n")
          Lua_f:close()
          return true
      else
          Lua_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          Lua_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          Lua_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== lists(l) quit(q)")
          return false
      end
    end
    return true
  end

  -- Reader
  local function Lua_read_file(Lua_path)
    local Lua_f = io.open(Lua_path, "r")
    if not Lua_f then
      print("❌ Gagal membuka ebook.")
      return
    end

    local content = Lua_f:read("*a")
    Lua_f:close()

    print(content .. "\n")
    print("--------------------------------------------")
    print("=================== Quit(q) Lists(l) === END")
  end

