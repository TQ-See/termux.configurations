  local function KTP_validate_file(KTP_path)
    local KTP_f, err = io.open(KTP_path, "r")
    
    -- 1. Blok Pembuatan File (Jika file belum ada)
    if not KTP_f then
      KTP_f = io.open(KTP_path, "w")
      if KTP_f then
          KTP_f:write(KTP_Header)
          KTP_f:write("\n")
          KTP_f:close()
          return true
      else
          KTP_cmd("echo -w ============ ⚠️ ACCESE DENIED =============")
          KTP_cmd("echo -e 'Restricted Launcher Permissions: The launcher cannot access this system file due to limited permissions. Please ensure you are only accessing files generated by the launcher itself.'")
          print("\nHow to fix this:\n")
          print("1. Delete the existing file.")
          print("2. Re-run the script and select your target\n   index.")
          print("3. The launcher will automatically\n   regenerate the file using the correct\n   template.\n")
          KTP_cmd("echo -s Once regenerated, you can manually edit the file without any issues.")
          print("\n--------------------------------------------")
          print("=========================== lists(l) quit(q)")
          return false
      end
    end
    return true
  end

